#!/usr/bin/env python3
"""Generate the SindhOS topi logo (original artwork, drawn from geometry).

  python3 branding/topi/gen_topi.py

Writes branding/topi/topi.svg (detailed: boot splash, About, installer) and
branding/topi/topi-small.svg (taskbar menu button, 24-32 px).

A traditional Sindhi topi seen at a slight 3/4 angle so the crown and the
front both show: cylindrical cap, arched cut-out at the front, deep maroon
base, navy bands, white dots along the top rim and bottom edge, a star/sun
medallion on the crown and diamond/cross patterns with white motifs on the
sides.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MAROON, MAROON_D, MAROON_L = "#8E1A22", "#4E0B10", "#B32A31"
NAVY, NAVY_D = "#1F2A5A", "#121937"
WHITE, CREAM, INSIDE, OUTLINE = "#FFFFFF", "#F6F1E7", "#26070A", "#2A0508"


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def arc_band(cx, rx, ry, y1, y2):
    """Front part of a cylinder between heights y1 (top) and y2 (bottom)."""
    return (f"M{f(cx - rx)},{f(y1)} A{f(rx)},{f(ry)} 0 0 0 {f(cx + rx)},{f(y1)} "
            f"L{f(cx + rx)},{f(y2)} A{f(rx)},{f(ry)} 0 0 1 {f(cx - rx)},{f(y2)} Z")


def on_cylinder(cx, rx, ry, h, deg):
    """Point on the front of the cylinder at angle deg (0 = facing us)."""
    a = math.radians(deg)
    return cx + rx * math.sin(a), h + ry * math.cos(a), math.cos(a)


def star(cx, cy, r_out, r_in, n, squash, rot=-90):
    pts = []
    for i in range(2 * n):
        a = math.radians(rot + 180 * i / n)
        r = r_out if i % 2 == 0 else r_in
        pts.append(f"{f(cx + r * math.cos(a))},{f(cy + r * math.sin(a) * squash)}")
    return " ".join(pts)


def arch_path(cx, w, top, bottom, closed=True):
    """Pointed (Mughal) arch from the bottom edge up to `top`. closed=False
    leaves the foot open (for the trim line)."""
    h = w / 2
    shoulder = top + w * 0.55
    return (f"M{f(cx - h)},{f(bottom)} L{f(cx - h)},{f(shoulder)} "
            f"C{f(cx - h)},{f(top + w * 0.18)} {f(cx - w * 0.12)},{f(top + w * 0.06)} {f(cx)},{f(top)} "
            f"C{f(cx + w * 0.12)},{f(top + w * 0.06)} {f(cx + h)},{f(top + w * 0.18)} {f(cx + h)},{f(shoulder)} "
            f"L{f(cx + h)},{f(bottom)}" + (" Z" if closed else ""))


def detailed():
    S = 256
    cx, rx, ry = 128, 94, 30
    top, bot = 82, 196                      # centre lines of crown and bottom ellipses
    band_top = (top + 6, top + 30)          # navy band under the rim
    band_bot = (bot - 26, bot - 2)          # navy band at the bottom
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}" width="{S}" height="{S}">',
           "<!-- SindhOS topi: traditional Sindhi cap, original artwork "
           "(generated by branding/topi/gen_topi.py) -->",
           "<defs>",
           f'<linearGradient id="body" x1="0" x2="1"><stop offset="0" stop-color="{MAROON_D}"/>'
           f'<stop offset="0.3" stop-color="{MAROON}"/><stop offset="0.5" stop-color="{MAROON_L}"/>'
           f'<stop offset="0.75" stop-color="{MAROON}"/><stop offset="1" stop-color="{MAROON_D}"/></linearGradient>',
           f'<linearGradient id="navy" x1="0" x2="1"><stop offset="0" stop-color="{NAVY_D}"/>'
           f'<stop offset="0.5" stop-color="{NAVY}"/><stop offset="1" stop-color="{NAVY_D}"/></linearGradient>',
           f'<radialGradient id="crown" cx="0.5" cy="0.45" r="0.6"><stop offset="0" stop-color="{MAROON_L}"/>'
           f'<stop offset="1" stop-color="{MAROON}"/></radialGradient>',
           f'<linearGradient id="inside" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#14040A"/>'
           f'<stop offset="1" stop-color="{INSIDE}"/></linearGradient>',
           f'<clipPath id="bodyclip"><path d="{arc_band(cx, rx, ry, top, bot)}"/></clipPath>',
           "</defs>"]
    # body
    out.append(f'<path d="{arc_band(cx, rx, ry, top, bot)}" fill="url(#body)"/>')
    out.append('<g clip-path="url(#bodyclip)">')
    for y1, y2 in (band_top, band_bot):
        out.append(f'<path d="{arc_band(cx, rx, ry, y1, y2)}" fill="url(#navy)"/>')
        # thin white lines edging the bands
        for y in (y1, y2):
            out.append(f'<path d="M{f(cx - rx)},{f(y)} A{rx},{ry} 0 0 0 {f(cx + rx)},{f(y)}" '
                       f'fill="none" stroke="{CREAM}" stroke-width="1.6" opacity="0.85"/>')
    # diamonds with white cross motifs on the sides, small dots in the top band
    mid = (band_top[1] + band_bot[0]) / 2 - 2
    for deg in range(-78, 79, 16):
        if abs(deg) < 28:
            continue                        # the arch is here
        x, y, c = on_cylinder(cx, rx, ry, mid, deg)
        w, h = 11 * c, 15
        out.append(f'<path d="M{f(x)},{f(y - h)} L{f(x + w)},{f(y)} L{f(x)},{f(y + h)} L{f(x - w)},{f(y)} Z" '
                   f'fill="{NAVY}" stroke="{CREAM}" stroke-width="{f(1.2 * c + 0.3)}"/>')
        out.append(f'<path d="M{f(x - 4.5 * c)},{f(y)} H{f(x + 4.5 * c)} M{f(x)},{f(y - 6)} V{f(y + 6)}" '
                   f'stroke="{WHITE}" stroke-width="{f(1.6 * c + 0.3)}" stroke-linecap="round"/>')
        for dy in (-h - 6, h + 6):
            out.append(f'<circle cx="{f(x)}" cy="{f(y + dy)}" r="{f(1.6 * c + 0.4)}" fill="{WHITE}"/>')
    for deg in range(-84, 85, 12):
        x, y, c = on_cylinder(cx, rx, ry, (band_top[0] + band_top[1]) / 2, deg)
        out.append(f'<path d="M{f(x)},{f(y - 5)} L{f(x + 4 * c)},{f(y)} L{f(x)},{f(y + 5)} L{f(x - 4 * c)},{f(y)} Z" '
                   f'fill="{MAROON_L}"/>')
        out.append(f'<circle cx="{f(x)}" cy="{f(y)}" r="{f(1.3 * c + 0.3)}" fill="{WHITE}"/>')
    out.append("</g>")
    # front arch: opening shows the dark inside, trimmed with white dots
    arch_bottom = bot + ry + 4
    AW, AT = 62, 118
    out.append('<g clip-path="url(#bodyclip)">')
    out.append(f'<path d="{arch_path(cx, AW, AT, arch_bottom)}" fill="url(#inside)"/>')
    out.append(f'<path d="{arch_path(cx, AW, AT, arch_bottom, closed=False)}" fill="none" stroke="{NAVY}" stroke-width="5"/>')
    out.append(f'<path d="{arch_path(cx, AW, AT, arch_bottom, closed=False)}" fill="none" stroke="{CREAM}" '
               f'stroke-width="2.4" stroke-dasharray="0.1 6.5" stroke-linecap="round"/>')
    out.append("</g>")
    # white dots along the bottom edge (not inside the arch)
    for deg in range(-82, 83, 7):
        x, y, c = on_cylinder(cx, rx, ry, bot - 6, deg)
        if abs(x - cx) < 37:
            continue
        out.append(f'<circle cx="{f(x)}" cy="{f(y)}" r="{f(1.9 * c + 0.5)}" fill="{WHITE}"/>')
    # crown with star/sun medallion
    out.append(f'<ellipse cx="{cx}" cy="{top}" rx="{rx}" ry="{ry}" fill="url(#crown)" stroke="{OUTLINE}" stroke-width="2"/>')
    out.append(f'<ellipse cx="{cx}" cy="{top}" rx="{rx * 0.8}" ry="{ry * 0.8}" fill="{NAVY}"/>')
    out.append(f'<ellipse cx="{cx}" cy="{top}" rx="{rx * 0.8}" ry="{ry * 0.8}" fill="none" stroke="{CREAM}" '
               f'stroke-width="1.4" stroke-dasharray="0.1 5" stroke-linecap="round"/>')
    sq = ry / rx
    out.append(f'<polygon points="{star(cx, top, 66, 36, 8, sq)}" fill="{MAROON_L}" stroke="{CREAM}" stroke-width="1.2"/>')
    out.append(f'<polygon points="{star(cx, top, 40, 22, 8, sq, rot=-67.5)}" fill="{MAROON_D}"/>')
    out.append(f'<ellipse cx="{cx}" cy="{top}" rx="16" ry="{f(16 * sq)}" fill="{CREAM}"/>')
    out.append(f'<ellipse cx="{cx}" cy="{top}" rx="8" ry="{f(8 * sq)}" fill="{MAROON}"/>')
    for i in range(8):
        a = math.radians(i * 45)
        out.append(f'<circle cx="{f(cx + 50 * math.cos(a))}" cy="{f(top + 50 * math.sin(a) * sq)}" r="2" fill="{WHITE}"/>')
    # white dots along the top rim
    for i in range(36):
        a = math.radians(i * 10)
        out.append(f'<circle cx="{f(cx + (rx - 6) * math.cos(a))}" cy="{f(top + (ry - 2.2) * math.sin(a))}" '
                   f'r="2.2" fill="{WHITE}"/>')
    # outline of the silhouette
    out.append(f'<path d="M{cx - rx},{top} L{cx - rx},{bot} A{rx},{ry} 0 0 0 {cx + rx},{bot} L{cx + rx},{top}" '
               f'fill="none" stroke="{OUTLINE}" stroke-width="2.4" stroke-linejoin="round"/>')
    out.append("</svg>")
    return "\n".join(out)


def small(tile):
    """Simplified version for 24-32 px: silhouette, front arch, maroon/navy."""
    S = 32
    cx, rx, ry = 16, 13.0, 4.2
    top, bot = 9.6, 23.4
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}" width="{S}" height="{S}">',
           "<!-- SindhOS topi, simplified for the taskbar (gen_topi.py) -->",
           "<defs>",
           f'<linearGradient id="b" x1="0" x2="1"><stop offset="0" stop-color="{MAROON_D}"/>'
           f'<stop offset="0.45" stop-color="{MAROON_L}"/><stop offset="1" stop-color="{MAROON_D}"/></linearGradient>',
           f'<clipPath id="c"><path d="{arc_band(cx, rx, ry, top, bot)}"/></clipPath>',
           "</defs>"]
    if tile:
        out.append(f'<rect x="0.5" y="0.5" width="31" height="31" rx="8" fill="{CREAM}" stroke="{MAROON}" stroke-width="1"/>')
    out.append(f'<path d="{arc_band(cx, rx, ry, top, bot)}" fill="url(#b)"/>')
    out.append(f'<g clip-path="url(#c)"><path d="{arc_band(cx, rx, ry, bot - 4, bot + 1)}" fill="{NAVY}"/></g>')
    out.append(f'<g clip-path="url(#c)"><path d="{arch_path(cx, 9.0, 14.6, bot + ry + 1)}" fill="{INSIDE}"/></g>')
    out.append(f'<ellipse cx="{cx}" cy="{top}" rx="{rx}" ry="{ry}" fill="{NAVY}" stroke="{OUTLINE}" stroke-width="0.7"/>')
    out.append(f'<polygon points="{star(cx, top, 8.0, 4.0, 8, ry / rx)}" fill="{MAROON_L}"/>')
    out.append(f'<ellipse cx="{cx}" cy="{top}" rx="1.6" ry="0.7" fill="{WHITE}"/>')
    for deg in (-62, -40, 40, 62):
        x, y, c = on_cylinder(cx, rx, ry, bot - 2.2, deg)
        out.append(f'<circle cx="{f(x)}" cy="{f(y)}" r="0.9" fill="{WHITE}"/>')
    out.append(f'<path d="M{f(cx - rx)},{top} L{f(cx - rx)},{bot} A{rx},{ry} 0 0 0 {f(cx + rx)},{bot} L{f(cx + rx)},{top}" '
               f'fill="none" stroke="{OUTLINE}" stroke-width="0.8" stroke-linejoin="round"/>')
    out.append("</svg>")
    return "\n".join(out)


if __name__ == "__main__":
    for name, svg in (("topi.svg", detailed()), ("topi-small.svg", small(tile=True)),
                      ("topi-small-notile.svg", small(tile=False))):
        with open(os.path.join(HERE, name), "w") as fh:
            fh.write(svg + "\n")
        print("wrote", os.path.join(HERE, name))
