#!/usr/bin/env python3
"""Generate the SindhOS xfwm4 window themes (title bars and buttons).

  python3 branding/theme/gen_xfwm4.py branding/theme

writes branding/theme/SindhOS-Light/xfwm4 and .../SindhOS-Dark/xfwm4 (the
generated PNGs are committed, so the build doesn't need Pillow).
Original artwork, drawn with Pillow: flat title bar with rounded top corners,
buttons on the right in the order minimize, maximize, close, shown as – □ ×.
Use with the xfwm4 setting button_layout "|HMC".
"""
import os
import sys

from PIL import Image, ImageDraw

SS = 4          # supersampling factor for smooth edges
TITLE_H = 34    # title bar height
RADIUS = 10     # rounded top corners
BTN_W = 34      # button cell width
HOVER = 26      # hover square size
GLYPH = 10      # glyph size (– □ ×)

VARIANTS = {
    "SindhOS-Light": dict(
        bg_active="#EFEDE8", bg_inactive="#F6F5F2",
        border_active="#CFCBC3", border_inactive="#DEDBD5",
        fg_active="#22232A", fg_inactive="#9A9AA0",
        hover=(0, 0, 0, 20), pressed=(0, 0, 0, 38),
        close_hover="#9B1B1E", close_pressed="#7A1417",
    ),
    "SindhOS-Dark": dict(
        bg_active="#212435", bg_inactive="#1B1D2A",
        border_active="#0D0E15", border_inactive="#0D0E15",
        fg_active="#ECECF1", fg_inactive="#7D8096",
        hover=(255, 255, 255, 22), pressed=(255, 255, 255, 40),
        close_hover="#B3262A", close_pressed="#8E1C20",
    ),
}


def rgba(c):
    if isinstance(c, tuple):
        return c
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def down(img):
    return img.resize((img.width // SS, img.height // SS), Image.LANCZOS)


def title_top(v, state):
    """A strip 2*RADIUS+1 wide: [rounded corner][1 px middle][rounded corner]."""
    w, h = 2 * RADIUS + 1, TITLE_H
    big = Image.new("RGBA", (w * SS, h * SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    d.rounded_rectangle([0, 0, w * SS - 1, (h + RADIUS) * SS], radius=RADIUS * SS,
                        fill=rgba(v[f"bg_{state}"]), outline=rgba(v[f"border_{state}"]), width=SS)
    return down(big)


def button(v, kind, state):
    """kind: hide | maximize | maximize-toggled | close | blank."""
    img = Image.new("RGBA", (BTN_W * SS, TITLE_H * SS), rgba(v["bg_active" if state != "inactive" else "bg_inactive"]))
    # top border line, so buttons continue the title bar's 1 px edge
    ImageDraw.Draw(img).rectangle([0, 0, img.width, SS - 1],
                                  fill=rgba(v["border_active" if state != "inactive" else "border_inactive"]))
    if kind == "blank":
        return down(img)
    d = ImageDraw.Draw(img)
    cx, cy = BTN_W * SS / 2, TITLE_H * SS / 2 + SS / 2
    fg = rgba(v["fg_inactive"] if state == "inactive" else v["fg_active"])
    if state in ("prelight", "pressed"):
        if kind == "close":
            bg = rgba(v["close_hover" if state == "prelight" else "close_pressed"])
            fg = (255, 255, 255, 255)
        else:
            bg = v["hover" if state == "prelight" else "pressed"]
        hs = HOVER * SS / 2
        layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
        ImageDraw.Draw(layer).rounded_rectangle([cx - hs, cy - hs, cx + hs, cy + hs], radius=7 * SS, fill=bg)
        img = Image.alpha_composite(img, layer)
        d = ImageDraw.Draw(img)
    g = GLYPH * SS / 2
    lw = round(1.4 * SS)
    if kind == "hide":                      # –
        d.line([cx - g, cy + g * 0.15, cx + g, cy + g * 0.15], fill=fg, width=lw)
    elif kind == "maximize":                # □
        d.rectangle([cx - g * 0.9, cy - g * 0.9, cx + g * 0.9, cy + g * 0.9], outline=fg, width=lw)
    elif kind == "maximize-toggled":        # two overlapping squares
        o = g * 0.35
        d.rectangle([cx - g * 0.9 + o, cy - g * 0.9 - o, cx + g * 0.9 + o, cy + g * 0.9 - o], outline=fg, width=lw)
        d.rectangle([cx - g * 0.9 - o, cy - g * 0.9 + o, cx + g * 0.9 - o, cy + g * 0.9 + o],
                    fill=img.getpixel((int(cx), int(cy))), outline=fg, width=lw)
    elif kind == "close":                   # ×
        d.line([cx - g * 0.85, cy - g * 0.85, cx + g * 0.85, cy + g * 0.85], fill=fg, width=lw)
        d.line([cx - g * 0.85, cy + g * 0.85, cx + g * 0.85, cy - g * 0.85], fill=fg, width=lw)
    return down(img)


THEMERC = """# SindhOS window theme (generated by branding/theme/gen_xfwm4.py)
button_offset=6
button_spacing=0
full_width_title=true
show_app_icon=false
title_horizontal_offset=0
title_vertical_offset_active=1
title_vertical_offset_inactive=1
title_shadow_active=false
title_shadow_inactive=false
active_text_color={fg_active}
inactive_text_color={fg_inactive}
active_border_color={border_active}
inactive_border_color={border_inactive}
"""


def generate(out):
    for name, v in VARIANTS.items():
        d = os.path.join(out, name, "xfwm4")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "themerc"), "w") as f:
            f.write(THEMERC.format(**v))
        for state in ("active", "inactive"):
            top = title_top(v, state)
            top.crop((0, 0, RADIUS, TITLE_H)).save(f"{d}/top-left-{state}.png")
            top.crop((RADIUS + 1, 0, 2 * RADIUS + 1, TITLE_H)).save(f"{d}/top-right-{state}.png")
            mid = top.crop((RADIUS, 0, RADIUS + 1, TITLE_H))
            for i in range(1, 6):
                mid.save(f"{d}/title-{i}-{state}.png")
            edge = Image.new("RGBA", (1, 1), rgba(v[f"border_{state}"]))
            for part in ("left", "right", "bottom", "bottom-left", "bottom-right"):
                edge.save(f"{d}/{part}-{state}.png")
        for kind in ("hide", "maximize", "maximize-toggled", "close"):
            for state in ("active", "inactive", "prelight", "pressed"):
                button(v, kind, state).save(f"{d}/{kind}-{state}.png")
        # Buttons SindhOS doesn't show; xfwm4 still expects the files.
        for kind in ("menu", "shade", "shade-toggled", "stick", "stick-toggled"):
            for state in ("active", "inactive", "prelight", "pressed"):
                button(v, "blank", state if state == "inactive" else "active").save(f"{d}/{kind}-{state}.png")
        print("wrote", d)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    generate(sys.argv[1])
