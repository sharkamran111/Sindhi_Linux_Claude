#!/usr/bin/env python3
"""Generate the Roman Sindhi input method and keyboard guide from layout.py.

Run from the repo root:  python3 keyboard/gen.py
"""
import html
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
from layout import LOWER, UPPER, MARKS, PUNCT  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
INC = ROOT / "config" / "includes.chroot"


def mim() -> str:
    def esc(s: str) -> str:
        return s.replace("\\", "\\\\").replace('"', '\\"')

    rows = []
    for table in (LOWER, UPPER):
        for k, v in table.items():
            rows.append(f'  ("{esc(k)}" "{esc(v)}")')
    for k, v, *_ in MARKS + PUNCT:
        rows.append(f'  ("{esc(k)}" "{esc(v)}")')
    return (
        ";; Roman Sindhi (phonetic) input method for Sindhi Linux.\n"
        ";; Generated by keyboard/gen.py from keyboard/layout.py. Do not edit by hand.\n\n"
        "(input-method sd roman-sindhi)\n\n"
        '(description "Roman Sindhi: type Sindhi letters on an English keyboard")\n\n'
        '(title "سنڌي")\n\n'
        "(map\n (trans\n" + "\n".join(rows) + "))\n\n"
        "(state\n (init\n  (trans)))\n"
    )


def guide() -> str:
    data = {
        "rows": [list("qwertyuiop"), list("asdfghjkl"), list("zxcvbnm")],
        "lower": LOWER,
        "upper": UPPER,
    }
    marks = "\n".join(
        f'<tr><td><kbd>{html.escape(k)}</kbd></td><td class="sd big">'
        f'{"ـ" + v if v in chr(0x64E) + chr(0x650) + chr(0x64F) + chr(0x651) + chr(0x652) else v}'
        f'</td><td>{html.escape(en)}</td><td class="sd">{sd}</td></tr>'
        for k, v, en, sd in MARKS
    )
    punct = "\n".join(
        f'<tr><td><kbd>{html.escape(k)}</kbd></td><td class="sd big">{v}</td>'
        f'<td>{html.escape(en)}</td><td class="sd">{sd}</td></tr>'
        for k, v, en, sd in PUNCT
    )
    tpl = (ROOT / "keyboard" / "guide.html.in").read_text(encoding="utf-8")
    return (
        tpl.replace("@DATA@", json.dumps(data, ensure_ascii=False))
        .replace("@MARKS@", marks)
        .replace("@PUNCT@", punct)
    )


def main() -> None:
    out_mim = INC / "usr/share/m17n/sd-roman-sindhi.mim"
    out_guide = INC / "usr/share/sindhi-linux/keyboard-guide/index.html"
    for p in (out_mim, out_guide):
        p.parent.mkdir(parents=True, exist_ok=True)
    out_mim.write_text(mim(), encoding="utf-8")
    out_guide.write_text(guide(), encoding="utf-8")
    print("wrote", out_mim.relative_to(ROOT))
    print("wrote", out_guide.relative_to(ROOT))


if __name__ == "__main__":
    main()
